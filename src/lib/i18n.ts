type MessageKey = keyof typeof messages.en;
type Params = Record<string, string | number>;

export function normalizeLocale(input: string | undefined | null): LocaleCode {
  if (!input) return FALLBACK;
  const lower = input.toLowerCase();
  const exact = lower === "tl" ? "fil" : lower;
  if (localeSet.has(exact)) return exact as LocaleCode;
  const base = exact.split("-")[0];
  if (localeSet.has(base)) return base as LocaleCode;
  return FALLBACK;
}

export function systemLocale(): LocaleCode {
  return normalizeLocale(navigator.language);
}

export function languageForAi(locale: LocaleCode): string {
  return LOCALES.find((l) => l.code === locale)?.aiName ?? "English";
}

export async function getStoredLocale(): Promise<LocaleCode> {
  const stored = await chrome.storage.local.get(STORAGE_KEY);
  const value = stored[STORAGE_KEY];
  if (typeof value === "string") return normalizeLocale(value);
  const detected = systemLocale();
  await setStoredLocale(detected);
  return detected;
}

export async function setStoredLocale(locale: LocaleCode): Promise<void> {
  await chrome.storage.local.set({ [STORAGE_KEY]: locale });
}

export function onStoredLocaleChanged(cb: (locale: LocaleCode) => void): void {
  chrome.storage.onChanged.addListener((changes, area) => {
    if (area !== "local") return;
    const next = changes[STORAGE_KEY]?.newValue;
    if (typeof next === "string") cb(normalizeLocale(next));
  });
}

export function t(
  locale: LocaleCode,
  key: MessageKey,
  params: Params = {},
): string {
  const dict = messages[locale] as Partial<Record<MessageKey, string>>;
  const fallback = messages.en[key];
  const template = dict[key] ?? fallback ?? key;
  return Object.entries(params).reduce(
    (result, [name, value]) => result.split(`{${name}}`).join(String(value)),
    template,
  );
}
